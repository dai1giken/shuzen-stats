def period_text(lo: int | None, hi: int | None) -> str:
    if lo is None:
        return "－"
    return f"{lo}年" if lo == hi else f"{lo}〜{hi}年"


def _norm(s: str) -> str:
    """原典テキストの表記ゆれを吸収する。

    PDF から抜いた生テキストは、セル内で折り返された箇所に改行が入り、
    全角スペースや半角スペースも混ざる。**改行と空白を落として比べる。**
    波ダッシュは原典が「～」、こちらの表記が「〜」で別の文字なのでそろえる。
    """
    s = s.replace("〜", "～")
    return re.sub(r"[\s　]+", "", s)


def verify() -> tuple[int, list[str]]:
    """書き写した1行ずつが、原典の生テキストに実在するか確かめる。

    周期がその行のものだと言えるのは、原典の中で周期が**隣の欄とくっついて
    現れている**とき。PDF から抜いたテキストは列の順番が崩れるので、
    くっつく相手は2通りありうる。

      「工事区分 ＋ 周期」   例「打替12～15年」
      「周期 ＋ 修繕方法」   例「24～30年既存屋根材を全面撤去の上…」

    **どちらか一方が見つかれば可**とする（傾斜屋根の「撤去・葺替」のように、
    工事区分だけが離れた位置に飛ぶ行が実際にある）。両方とも見つからなければ、
    周期を別の行から取り違えている可能性があるので落とす。

    対象部位等も原典に実在するか見る。原典でセルが複数行に分かれているものは
    こちら側で「／」を挟んであるので、**「／」で割ってそれぞれ**を確かめる。
    工事区分が空欄の項目（調査・診断など）は周期だけ見る。
    """
    if not REF.exists():
        return 0, [f"原典テキストがありません: {REF}"]
    ref = _norm(REF.read_text(encoding="utf-8"))

    bad: list[str] = []
    rows = list(CYCLES) + [SENYU]
    for _dai, chu, item, bui, kubun, lo, hi, how in rows:
        if lo is None:
            continue  # 「－」は照合対象にしない
        per = period_text(lo, hi)
        cands = [kubun + per] + ([per + how] if how else [])
        if not any(_norm(c) in ref for c in cands):
            bad.append(f"{chu} {item}／{kubun} {per} が原典に見つかりません")
        for part in filter(None, bui.split("／")):
            if _norm(part) not in ref:
                bad.append(f"{chu} {item}／対象部位「{part[:24]}…」が原典に見つかりません")
    return len(rows), bad


def main() -> None:
    n, bad = verify()
    print(f"{SOURCE_NAME}（{SOURCE_REVISION}）")
    print(f"  {n} 行を原典と突合しました")
    if bad:
        for b in bad:
            print("  ✗ " + b)
        sys.exit(f"{len(bad)} 件が原典と一致しません。")
    print("  ✓ 全行が原典のテキストに一致しました")


if __name__ == "__main__":
    main()
